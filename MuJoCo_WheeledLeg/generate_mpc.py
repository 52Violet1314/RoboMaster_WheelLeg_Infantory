"""Offline constant-move MPC design and deterministic Python / C table export.

Prediction: x[k+1] = Ad*x[k] + Bd*u, u[0] = ... = u[N-1].
Cost: sum(x[k]'Q*x[k], k=1..N-1) + x[N]'P*x[N] + N*u'R*u.
P is the discrete infinite-horizon LQR terminal cost. Only input box
constraints are imposed. N > 1 is a prediction horizon, not N free moves.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy import linalg

import lqr_k
from explicit_mpc import REGIONS, FREE_MASKS

ROOT = Path(__file__).resolve().parent
DEFAULT_LENGTHS = np.unique(np.r_[np.arange(0.09, 0.451, 0.01).round(5), 0.1339, 0.135])
BODY = dict(R_w=0.06, R_l=0.222, l_c=0.0024, m_w=0.512, m_l=1.056,
            m_b=16.862, I_z=0.189, I_b=0.3129)
Q = np.diag([20., 1., 4000., 1., 35000., 10., 35000., 10., 40000., 1.])
R = lqr_k.R_DEFAULT


def design(length, dt=0.001, horizon=3):
    if horizon < 1 or dt <= 0:
        raise ValueError("horizon and dt must be positive")
    a, b = lqr_k.compute_AB(lqr_k.leg_params(length, BODY))
    zoh = np.zeros((14, 14))
    zoh[:10, :10], zoh[:10, 10:] = a, b
    disc = linalg.expm(zoh * dt)
    ad, bd = disc[:10, :10], disc[:10, 10:]
    p = linalg.solve_discrete_are(ad, bd, Q, R)
    h, f = horizon * R.copy(), np.zeros((4, 10))
    ax, bu = np.eye(10), np.zeros((10, 4))
    for k in range(1, horizon + 1):
        ax, bu = ad @ ax, ad @ bu + bd
        weight = p if k == horizon else Q
        h += bu.T @ weight @ bu
        f += bu.T @ weight @ ax
    h = (h + h.T) * 0.5
    gain = linalg.solve(h, f, assume_a="pos")
    h /= np.max(np.diag(h))  # Scaling does not change the optimal control.
    correction = np.zeros((16, 4, 4))
    for mask in range(16):
        free = [i for i in range(4) if mask & (1 << i)]
        active = [i for i in range(4) if i not in free]
        if free and active:
            correction[mask][np.ix_(free, active)] = -linalg.solve(
                h[np.ix_(free, free)], h[np.ix_(free, active)], assume_a="pos")
    radius = max(abs(np.linalg.eigvals(ad - bd @ gain)))
    if radius >= 1:
        raise ValueError(f"Unconstrained discrete loop unstable at {length}: {radius}")
    return gain, h, correction, float(radius)


def c_array(array):
    array = np.asarray(array)
    if array.ndim == 0:
        if array.dtype.kind in "iu":
            return str(int(array))
        number = format(float(array), ".9g")
        if "." not in number and "e" not in number:
            number += ".0"
        return number + "f"
    return "{" + ",".join(c_array(row) for row in array) + "}"


def generate(dt=0.001, horizon=3):
    designs = [design(length, dt, horizon) for length in DEFAULT_LENGTHS]
    gains, hessians, corrections, radii = map(np.array, zip(*designs))
    arrays = dict(version=np.array(1), dt=np.array(dt), horizon=np.array(horizon),
                  lengths=DEFAULT_LENGTHS.copy(), Q=Q,
                  gain=gains.astype(np.float32), hessian=hessians.astype(np.float32),
                  correction=corrections.astype(np.float32))
    np.savez_compressed(ROOT / "mpc_tables.npz", **arrays)
    embedded = ROOT / "embedded_mpc"
    embedded.mkdir(exist_ok=True)
    header = f'''/* Generated by ../generate_mpc.py. Do not edit. */
#ifndef WHEELLEG_MPC_TABLES_H
#define WHEELLEG_MPC_TABLES_H
#include <stdint.h>
#define MPC_MODEL_COUNT {len(DEFAULT_LENGTHS)}
#define MPC_REGION_COUNT 81
#define MPC_SAMPLE_TIME {c_array(np.array(dt))}
#define MPC_PREDICTION_STEPS {horizon}
static const float mpc_lengths[MPC_MODEL_COUNT] = {c_array(DEFAULT_LENGTHS)};
static const float mpc_gain[MPC_MODEL_COUNT][4][10] = {c_array(gains.astype(np.float32))};
static const float mpc_hessian[MPC_MODEL_COUNT][4][4] = {c_array(hessians.astype(np.float32))};
static const float mpc_correction[MPC_MODEL_COUNT][16][4][4] = {c_array(corrections.astype(np.float32))};
static const int8_t mpc_regions[81][4] = {c_array(REGIONS)};
static const uint8_t mpc_free_masks[81] = {c_array(FREE_MASKS)};
#endif
'''
    (embedded / "mpc_tables.h").write_text(header, encoding="utf-8")
    metadata = dict(sample_time_s=dt, prediction_steps=horizon, control_moves=1,
                    hold_input_over_prediction=True, models=len(DEFAULT_LENGTHS),
                    regions_per_model=81, coefficient_bytes=gains.astype("f4").nbytes
                    + hessians.astype("f4").nbytes + corrections.astype("f4").nbytes
                    + len(DEFAULT_LENGTHS) * 4 + REGIONS.nbytes + 81,
                    max_local_spectral_radius=float(max(radii)),
                    constraints="input box only; no state or terminal set constraints",
                    body=BODY, Q_diagonal=np.diag(Q).tolist(), R_diagonal=np.diag(R).tolist())
    (embedded / "design.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dt", type=float, default=0.001)
    parser.add_argument("--horizon", type=int, default=3)
    args = parser.parse_args()
    generate(args.dt, args.horizon)
