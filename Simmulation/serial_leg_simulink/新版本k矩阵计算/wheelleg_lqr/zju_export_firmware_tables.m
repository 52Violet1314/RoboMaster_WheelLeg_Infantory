function zju_export_firmware_tables(Qdiag, Rdiag)
%ZJU_EXPORT_FIRMWARE_TABLES Generate the deployed C++ K/theta tables.
% This is the single export path for the exact 41-point schedule validated
% by zju_firmware_schedule.  Do not manually edit individual table entries.

if nargin < 1, Qdiag = []; end
if nargin < 2, Rdiag = []; end
schedule = zju_firmware_schedule(Qdiag, Rdiag, false);

this_dir = fileparts(mfilename('fullpath'));
firmware_root = fullfile(this_dir, '..', '..', '..', '..', ...
    'RoboMaster_InfantoryV2.1.4', 'APP');
write_k_table(fullfile(firmware_root, 'src', 'app_K_value.cpp'), schedule);
write_theta_table(fullfile(firmware_root, 'src', 'app_leg_angle_target.cpp'), schedule);
write_theta_header(fullfile(firmware_root, 'inc', 'app_leg_angle_target.hpp'));

fprintf('Exported 41 K tables and 41 theta targets for com_forward_m = 0 mm.\n');
end

function write_k_table(path, schedule)
fid = fopen(path, 'w');
assert(fid >= 0, 'Unable to write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, '#include "app_K_value.hpp"\n#include <math.h>\n\n');
fprintf(fid, '/* Auto-generated by zju_export_firmware_tables.m.\n');
fprintf(fid, ' * Q = diag([40, 4, 400, 2, 35000, 9, 35000, 9, 40000, 4]).\n');
fprintf(fid, ' * R = diag([10, 10, 1, 1]). Body CoM fore-aft offset = 0 mm.\n');
fprintf(fid, ' * State columns: X,dX,yaw,dyaw,thetaL,dthetaL,thetaR,dthetaR,-pitch,-dpitch.\n');
fprintf(fid, ' * Input rows: Fw_L,Fw_R,Tp_L,Tp_R.\n */\n\n');
fprintf(fid, 'const LQR_K_Schedule_t LQR_K_Schedule[LQR_K_SCHEDULE_COUNT] = {\n');
for n = 1:numel(schedule.length_m)
    fprintf(fid, '    {%.3ff, {\n', schedule.length_m(n));
    for row = 1:4
        fprintf(fid, '        {');
        for col = 1:10
            if col > 1, fprintf(fid, ', '); end
            fprintf(fid, '%+.9ff', schedule.gain(n, row, col));
        end
        if row < 4, fprintf(fid, '},\n'); else, fprintf(fid, '}\n'); end
    end
    if n < numel(schedule.length_m), fprintf(fid, '    }},\n'); else, fprintf(fid, '    }}\n'); end
end
fprintf(fid, '};\n\n');
fprintf(fid, [ ...
'void LQR_K_GetInterpolated(float leg_length_m, K_Fixed_Leg_t output) {\n' ...
'    if (!isfinite(leg_length_m)) leg_length_m = LQR_K_SCHEDULE_MIN_LENGTH_M;\n' ...
'    if (leg_length_m <= LQR_K_Schedule[0].leg_length_m) {\n' ...
'        for (uint32_t row = 0; row < 4U; ++row)\n' ...
'            for (uint32_t col = 0; col < 10U; ++col) output[row][col] = LQR_K_Schedule[0].gain[row][col];\n' ...
'        return;\n' ...
'    }\n' ...
'    if (leg_length_m >= LQR_K_Schedule[LQR_K_SCHEDULE_COUNT - 1U].leg_length_m) {\n' ...
'        for (uint32_t row = 0; row < 4U; ++row)\n' ...
'            for (uint32_t col = 0; col < 10U; ++col) output[row][col] = LQR_K_Schedule[LQR_K_SCHEDULE_COUNT - 1U].gain[row][col];\n' ...
'        return;\n' ...
'    }\n' ...
'    uint32_t lower = (uint32_t)((leg_length_m - LQR_K_SCHEDULE_MIN_LENGTH_M) / LQR_K_SCHEDULE_STEP_M);\n' ...
'    if (lower >= LQR_K_SCHEDULE_COUNT - 1U) lower = LQR_K_SCHEDULE_COUNT - 2U;\n' ...
'    const float lo = LQR_K_Schedule[lower].leg_length_m;\n' ...
'    const float hi = LQR_K_Schedule[lower + 1U].leg_length_m;\n' ...
'    const float ratio = (leg_length_m - lo) / (hi - lo);\n' ...
'    for (uint32_t row = 0; row < 4U; ++row)\n' ...
'        for (uint32_t col = 0; col < 10U; ++col)\n' ...
'            output[row][col] = LQR_K_Schedule[lower].gain[row][col] +\n' ...
'                (LQR_K_Schedule[lower + 1U].gain[row][col] - LQR_K_Schedule[lower].gain[row][col]) * ratio;\n' ...
'}\n']);
end

function write_theta_table(path, schedule)
fid = fopen(path, 'w');
assert(fid >= 0, 'Unable to write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '#include "app_leg_angle_target.hpp"\n#include <stdint.h>\n\n');
fprintf(fid, '/* Auto-generated from 0 mm fore-aft CoM static equilibrium. */\n');
fprintf(fid, 'const LegAngleTargetParam_t LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT] = {\n');
for n = 1:numel(schedule.length_m)
    theta = schedule.theta_ref_rad(n);
    if abs(theta) < 5e-8, theta = 0; end
    fprintf(fid, '    {%.3ff, %+.9ff}%s\n', schedule.length_m(n), theta, ternary(n < numel(schedule.length_m), ',', ''));
end
fprintf(fid, '};\n\n');
fprintf(fid, [ ...
'LegAngleTargetParam_t LegAngleTarget_GetParam(float leg_length_m) {\n' ...
'    if (leg_length_m <= LegAngleTargetTable[0].leg_length_m) return LegAngleTargetTable[0];\n' ...
'    if (leg_length_m >= LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT - 1U].leg_length_m) return LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT - 1U];\n' ...
'    uint32_t lower = (uint32_t)((leg_length_m - LEG_ANGLE_TARGET_MIN_LENGTH_M) / LEG_ANGLE_TARGET_LENGTH_STEP_M);\n' ...
'    if (lower >= LEG_ANGLE_TARGET_TABLE_COUNT - 1U) lower = LEG_ANGLE_TARGET_TABLE_COUNT - 2U;\n' ...
'    const LegAngleTargetParam_t &lo = LegAngleTargetTable[lower];\n' ...
'    const LegAngleTargetParam_t &hi = LegAngleTargetTable[lower + 1U];\n' ...
'    const float ratio = (leg_length_m - lo.leg_length_m) / (hi.leg_length_m - lo.leg_length_m);\n' ...
'    return {leg_length_m, lo.theta_target_rad + (hi.theta_target_rad - lo.theta_target_rad) * ratio};\n' ...
'}\n\n' ...
'float LegAngleTarget_GetTheta(float leg_length_m) { return LegAngleTarget_GetParam(leg_length_m).theta_target_rad; }\n']);
end

function write_theta_header(path)
fid = fopen(path, 'w');
assert(fid >= 0, 'Unable to write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, [ ...
'#ifndef __APP_LEG_ANGLE_TARGET_HPP__\n#define __APP_LEG_ANGLE_TARGET_HPP__\n\n' ...
'/* Per-leg firmware theta target table, generated at a 0 mm fore-aft CoM offset. */\n' ...
'#define LEG_ANGLE_TARGET_TABLE_COUNT 41U\n#define LEG_ANGLE_TARGET_MIN_LENGTH_M 0.150f\n#define LEG_ANGLE_TARGET_LENGTH_STEP_M 0.005f\n\n' ...
'typedef struct { float leg_length_m; float theta_target_rad; } LegAngleTargetParam_t;\n\n' ...
'extern const LegAngleTargetParam_t LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT];\n' ...
'LegAngleTargetParam_t LegAngleTarget_GetParam(float leg_length_m);\n' ...
'float LegAngleTarget_GetTheta(float leg_length_m);\n\n#endif\n']);
end

function out = ternary(condition, yes, no)
if condition, out = yes; else, out = no; end
end
