function zju_export_firmware_tables(Qdiag, Rdiag)
%ZJU_EXPORT_FIRMWARE_TABLES Generate the deployed C++ K/theta tables.
% This is the single export path for the exact 41-point schedule validated
% by zju_firmware_schedule.  Do not manually edit individual table entries.

if nargin < 1, Qdiag = []; end
if nargin < 2, Rdiag = []; end
schedule = zju_firmware_schedule(Qdiag, Rdiag, false);
reference_parameters = zju_parameters_template(0.20);
com_forward_m = reference_parameters.l_c * sin(reference_parameters.phi_c);

this_dir = fileparts(mfilename('fullpath'));
firmware_root = fullfile(this_dir, '..', '..', '..', '..', ...
    'RoboMaster_InfantoryV2.1.4', 'APP');
write_k_table(fullfile(firmware_root, 'src', 'app_K_value.cpp'), schedule, ...
    schedule.Qdiag, schedule.Rdiag, com_forward_m);
write_theta_table(fullfile(firmware_root, 'src', 'app_leg_angle_target.cpp'), ...
    schedule, com_forward_m);
write_theta_header(fullfile(firmware_root, 'inc', 'app_leg_angle_target.hpp'), ...
    com_forward_m);

fprintf('Exported 41 K tables and 41 theta targets for com_forward_m = %.6f mm.\n', ...
    com_forward_m * 1e3);
end

function write_k_table(path, schedule, Qdiag, Rdiag, com_forward_m)
% Replace only the marked generated table.  app_K_value.cpp also contains
% hand-maintained feedback/limit functions and must never be regenerated as
% a whole file.
table_text = sprintf(['// BEGIN AUTO-GENERATED LQR K TABLE\n' ...
    '/* Auto-generated by zju_export_firmware_tables.m.\n' ...
    ' * Q = diag([%s]).\n' ...
    ' * R = diag([%s]). Body CoM fore-aft offset = %+.6f mm.\n' ...
    ' * State columns: X,dX,yaw,dyaw,thetaL,dthetaL,thetaR,dthetaR,-pitch,-dpitch.\n' ...
    ' * Input rows: Fw_L,Fw_R,Tp_L,Tp_R.\n */\n\n' ...
    'const LQR_K_Schedule_t LQR_K_Schedule[LQR_K_SCHEDULE_COUNT] = {\n'], ...
    vector_to_text(Qdiag), vector_to_text(Rdiag), com_forward_m * 1e3);
for n = 1:numel(schedule.length_m)
    table_text = [table_text sprintf('    {%.3ff, {\n', schedule.length_m(n))]; %#ok<AGROW>
    for row = 1:4
        table_text = [table_text '        {']; %#ok<AGROW>
        for col = 1:10
            if col > 1, table_text = [table_text ', ']; end %#ok<AGROW>
            table_text = [table_text sprintf('%+.9ff', schedule.gain(n, row, col))]; %#ok<AGROW>
        end
        if row < 4
            table_text = sprintf('%s},\n', table_text);
        else
            table_text = sprintf('%s}\n', table_text);
        end
    end
    if n < numel(schedule.length_m)
        table_text = sprintf('%s    }},\n', table_text);
    else
        table_text = sprintf('%s    }}\n', table_text);
    end
end
table_text = sprintf('%s};\n// END AUTO-GENERATED LQR K TABLE\n', table_text);
replace_marked_region(path, table_text);
end

function replace_marked_region(path, generated_text)
begin_marker = '// BEGIN AUTO-GENERATED LQR K TABLE';
end_marker = '// END AUTO-GENERATED LQR K TABLE';
source = fileread(path);
begin_at = strfind(source, begin_marker);
end_at = strfind(source, end_marker);
assert(numel(begin_at) == 1 && numel(end_at) == 1 && end_at > begin_at, ...
    'Expected exactly one valid generated K-table marker pair in %s.', path);

updated = [source(1:begin_at-1) generated_text source(end_at+length(end_marker):end)];
temporary_path = [path '.tmp'];
fid = fopen(temporary_path, 'w');
assert(fid >= 0, 'Unable to write %s.', temporary_path);
fprintf(fid, '%s', updated);
fclose(fid);
[ok, message] = movefile(temporary_path, path, 'f');
assert(ok, 'Unable to update %s: %s', path, message);
end

function text = vector_to_text(values)
text = strtrim(sprintf('%.9g ', values));
end

function write_theta_table(path, schedule, com_forward_m)
fid = fopen(path, 'w');
assert(fid >= 0, 'Unable to write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '#include "app_leg_angle_target.hpp"\n#include <stdint.h>\n\n');
fprintf(fid, ['/* Auto-generated from static equilibrium with fore-aft CoM ' ...
    'offset %+.6f mm. */\n'], com_forward_m * 1e3);
fprintf(fid, 'const LegAngleTargetParam_t LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT] = {\n');
for n = 1:numel(schedule.length_m)
    theta = schedule.theta_ref_rad(n);
    if abs(theta) < 5e-8, theta = 0; end
    fprintf(fid, '    {%.3ff, %+.9ff}%s\n', schedule.length_m(n), theta, ternary(n < numel(schedule.length_m), ',', ''));
end
fprintf(fid, '};\n\n');
fprintf(fid, [ ...
'LegAngleTargetParam_t LegAngleTarget_GetParam(float leg_length_m) {\n' ...
'    if (leg_length_m <= LegAngleTargetTable[0].leg_length_m) return LegAngleTargetTable[0];\n' ...
'    if (leg_length_m >= LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT - 1U].leg_length_m) return LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT - 1U];\n' ...
'    uint32_t lower = (uint32_t)((leg_length_m - LEG_ANGLE_TARGET_MIN_LENGTH_M) / LEG_ANGLE_TARGET_LENGTH_STEP_M);\n' ...
'    if (lower >= LEG_ANGLE_TARGET_TABLE_COUNT - 1U) lower = LEG_ANGLE_TARGET_TABLE_COUNT - 2U;\n' ...
'    const LegAngleTargetParam_t &lo = LegAngleTargetTable[lower];\n' ...
'    const LegAngleTargetParam_t &hi = LegAngleTargetTable[lower + 1U];\n' ...
'    const float ratio = (leg_length_m - lo.leg_length_m) / (hi.leg_length_m - lo.leg_length_m);\n' ...
'    return {leg_length_m, lo.theta_target_rad + (hi.theta_target_rad - lo.theta_target_rad) * ratio};\n' ...
'}\n\n' ...
'float LegAngleTarget_GetTheta(float leg_length_m) { return LegAngleTarget_GetParam(leg_length_m).theta_target_rad; }\n']);
end

function write_theta_header(path, com_forward_m)
fid = fopen(path, 'w');
assert(fid >= 0, 'Unable to write %s.', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, [ ...
'#ifndef __APP_LEG_ANGLE_TARGET_HPP__\n#define __APP_LEG_ANGLE_TARGET_HPP__\n\n' ...
'/* Per-leg firmware theta target table, generated at a %+.6f mm fore-aft CoM offset. */\n' ...
'#define LEG_ANGLE_TARGET_TABLE_COUNT 41U\n#define LEG_ANGLE_TARGET_MIN_LENGTH_M 0.150f\n#define LEG_ANGLE_TARGET_LENGTH_STEP_M 0.005f\n\n' ...
'typedef struct { float leg_length_m; float theta_target_rad; } LegAngleTargetParam_t;\n\n' ...
'extern const LegAngleTargetParam_t LegAngleTargetTable[LEG_ANGLE_TARGET_TABLE_COUNT];\n' ...
'LegAngleTargetParam_t LegAngleTarget_GetParam(float leg_length_m);\n' ...
'float LegAngleTarget_GetTheta(float leg_length_m);\n\n#endif\n'], com_forward_m * 1e3);
end

function out = ternary(condition, yes, no)
if condition, out = yes; else, out = no; end
end
