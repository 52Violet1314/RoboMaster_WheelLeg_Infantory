void LQR_K_GetInterpolated(float leg_length_m, K_Fixed_Leg_t output) {
    if (!isfinite(leg_length_m))
        leg_length_m = LQR_K_SCHEDULE_MIN_LENGTH_M;

    if (leg_length_m <= LQR_K_Schedule[0].leg_length_m) {
        for (uint32_t row = 0; row < 4U; ++row)
            for (uint32_t column = 0; column < 10U; ++column)
                output[row][column] = LQR_K_Schedule[0].gain[row][column];
        return;
    }

    if (leg_length_m >=
        LQR_K_Schedule[LQR_K_SCHEDULE_COUNT - 1U].leg_length_m) {
        for (uint32_t row = 0; row < 4U; ++row)
            for (uint32_t column = 0; column < 10U; ++column)
                output[row][column] =
                    LQR_K_Schedule[LQR_K_SCHEDULE_COUNT - 1U].gain[row][column];
        return;
    }

    const float table_index =
        (leg_length_m - LQR_K_SCHEDULE_MIN_LENGTH_M) /
        LQR_K_SCHEDULE_STEP_M;
    uint32_t lower_index = (uint32_t)table_index;
    if (lower_index >= LQR_K_SCHEDULE_COUNT - 1U)
        lower_index = LQR_K_SCHEDULE_COUNT - 2U;

    const float lower_length = LQR_K_Schedule[lower_index].leg_length_m;
    const float upper_length =
        LQR_K_Schedule[lower_index + 1U].leg_length_m;
    const float ratio =
        (leg_length_m - lower_length) / (upper_length - lower_length);

    for (uint32_t row = 0; row < 4U; ++row)
        for (uint32_t column = 0; column < 10U; ++column)
            output[row][column] =
                LQR_K_Schedule[lower_index].gain[row][column] +
                (LQR_K_Schedule[lower_index + 1U].gain[row][column] -
                 LQR_K_Schedule[lower_index].gain[row][column]) * ratio;
}
